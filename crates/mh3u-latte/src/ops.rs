//! The ALU instruction numbers of the R6xx/R7xx family: name, number of source operands and which slots may issue it. The numbers are
//! those of the family's open driver (Mesa's `r600_isa`), which documents them; this table is made from that list.

/// Which slot of a group an instruction may be issued in.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Slots {
    /// A vector slot or the transcendental one.
    Any,
    /// Only the transcendental slot (`t`): the scalar operations such as reciprocal and sine.
    Scalar,
    /// Only the vector slots (x, y, z, w).
    Vector,
    /// Uses all four vector slots together (the dot products, `CUBE`, `MAX4`).
    Reduction,
}

